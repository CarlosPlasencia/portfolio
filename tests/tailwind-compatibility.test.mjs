import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import postcss from 'postcss';
import tailwindcss from 'tailwindcss';
import autoprefixer from 'autoprefixer';

const require = createRequire(import.meta.url);
const consumers = ['tailwindcss', 'postcss-nested'];

test('both Tailwind selector-parser edges resolve to the patched version', () => {
  const tailwindRequire = createRequire(require.resolve('tailwindcss/package.json'));
  for (const consumer of consumers) {
    const consumerRequire = createRequire(tailwindRequire.resolve(`${consumer}/package.json`));
    assert.equal(consumerRequire('postcss-selector-parser/package.json').version, '7.1.6');
  }
});

test('patched parser preserves responsive, nested variant and apply output', async () => {
  const classes = 'flex md:grid dark:bg-blue-900 hover:text-blue-500 focus-visible:outline-none group-hover:opacity-75 peer-checked:block [&>span]:font-bold before:content-["_"] supports-[display:grid]:grid [&:is(:hover,:focus)]:underline';
  const result = await postcss([
    tailwindcss({ content: [{ raw: classes, extension: 'html' }], darkMode: 'class', theme: {}, plugins: [] }),
    autoprefixer({ overrideBrowserslist: ['last 2 versions'] }),
  ]).process('@tailwind utilities; .compatibility { @apply flex items-center gap-2 rounded-lg; }', { from: undefined });
  const rules = [];
  result.root.walkRules((rule) => {
    const context = [];
    for (let node = rule.parent; node?.type !== 'root'; node = node.parent) {
      context.unshift(`@${node.name} ${node.params}`);
    }
    rules.push({ context, selector: rule.selector, declarations: rule.nodes.filter((node) => node.type === 'decl').map((node) => [node.prop, node.value, !!node.important]) });
  });
  const fingerprint = createHash('sha256').update(JSON.stringify(rules)).digest('hex');
  // Golden output captured with the original 6.1.5 parser, not generated by the test.
  assert.equal(fingerprint, 'd6bea9ad480baa599a1d943b75fd6e972afaeafc737061c31f388e9cd4bc625f');
});
